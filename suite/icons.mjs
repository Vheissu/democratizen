export function drawGlyph(canvas, id, color) {
  const ctx = canvas.getContext('2d');
  ctx.clearRect(0, 0, canvas.width, canvas.height);
  const step = canvas.width / 10;
  ctx.fillStyle = color;
  glyphs[id].forEach((row, y) =>
    [...row].forEach((cell, x) => {
      if (cell === '1')
        ctx.fillRect((x + 1) * step, (y + 1) * step, step * 0.78, step * 0.78);
    }),
  );
}
